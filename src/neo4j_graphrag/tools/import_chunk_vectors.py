from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path
from typing import Any

from neo4j_graphrag.neo4j_indexes import create_vector_index


def _require_env(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        print(f"Missing env var: {name}", file=sys.stderr)
        sys.exit(1)
    return value


def _import_neo4j():
    try:
        import neo4j
    except ImportError as exc:
        raise ImportError(
            "Could not import neo4j Python driver. Install with `uv pip install neo4j`."
        ) from exc
    return neo4j


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Import chunk embeddings from documents_with_embeddings.jsonl into existing "
            "Neo4j Chunk nodes and create a vector index."
        )
    )
    parser.add_argument(
        "--documents-path",
        required=True,
        help="Path to documents_with_embeddings.jsonl generated by build_index.py.",
    )
    parser.add_argument(
        "--neo4j-uri",
        default=os.environ.get("NEO4J_URI", "bolt://127.0.0.1:7687"),
        help="Neo4j URI.",
    )
    parser.add_argument(
        "--neo4j-user",
        default=os.environ.get("NEO4J_USER", "neo4j"),
        help="Neo4j username.",
    )
    parser.add_argument(
        "--neo4j-database",
        default=os.environ.get("NEO4J_DATABASE"),
        help="Neo4j database name (optional).",
    )
    parser.add_argument(
        "--label",
        default="Chunk",
        help="Target node label. Defaults to Chunk.",
    )
    parser.add_argument(
        "--id-property",
        default="chunk_id",
        help="Node property used to match embeddings back to Neo4j nodes.",
    )
    parser.add_argument(
        "--embedding-property",
        default="embedding",
        help="Node property used to store the vector.",
    )
    parser.add_argument(
        "--vector-index-name",
        default=os.environ.get("NEO4J_VECTOR_INDEX", "chunk_embedding_index"),
        help="Neo4j vector index name.",
    )
    parser.add_argument(
        "--similarity-fn",
        choices=["cosine", "euclidean"],
        default="cosine",
        help="Similarity function for the vector index.",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=200,
        help="Number of embeddings to write per transaction.",
    )
    parser.add_argument(
        "--progress-every",
        type=int,
        default=1000,
        help="Print progress every N processed rows.",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Fail fast on malformed rows instead of skipping them.",
    )
    return parser


def _read_documents(path: Path, *, strict: bool) -> tuple[list[dict[str, Any]], int]:
    rows: list[dict[str, Any]] = []
    dim = 0
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            raw = line.strip()
            if not raw:
                continue
            try:
                payload = json.loads(raw)
            except json.JSONDecodeError as exc:
                if strict:
                    raise ValueError(f"Invalid JSON at {path}:{line_no}: {exc}") from exc
                continue

            chunk_id = payload.get("id")
            embedding = payload.get("embedding")
            if not isinstance(chunk_id, str) or not chunk_id.strip():
                if strict:
                    raise ValueError(f"Missing/invalid id at {path}:{line_no}")
                continue
            if not isinstance(embedding, list) or not embedding:
                if strict:
                    raise ValueError(f"Missing/invalid embedding at {path}:{line_no}")
                continue
            try:
                embedding_floats = [float(x) for x in embedding]
            except (TypeError, ValueError) as exc:
                if strict:
                    raise ValueError(f"Non-numeric embedding at {path}:{line_no}") from exc
                continue

            if not dim:
                dim = len(embedding_floats)
            elif len(embedding_floats) != dim:
                raise ValueError(
                    f"Inconsistent embedding dimension at {path}:{line_no}: "
                    f"expected {dim}, got {len(embedding_floats)}"
                )

            rows.append({"chunk_id": chunk_id.strip(), "embedding": embedding_floats})

    if not rows:
        raise ValueError(f"No valid embedding rows found in {path}")
    return rows, dim


def _upsert_batch_tx(
    tx: Any,
    *,
    rows: list[dict[str, Any]],
    label: str,
    id_property: str,
    embedding_property: str,
) -> tuple[int, int]:
    label_escaped = label.replace("`", "")
    id_property_escaped = id_property.replace("`", "")
    embedding_property_escaped = embedding_property.replace("`", "")
    query = f"""
    UNWIND $rows AS row
    OPTIONAL MATCH (n:`{label_escaped}` {{{id_property_escaped}: row.chunk_id}})
    FOREACH (_ IN CASE WHEN n IS NULL THEN [] ELSE [1] END |
      SET n.`{embedding_property_escaped}` = row.embedding
    )
    RETURN count(n) AS matched, size($rows) - count(n) AS missing
    """
    record = tx.run(query, rows=rows).single()
    matched = int(record["matched"] or 0) if record is not None else 0
    missing = int(record["missing"] or 0) if record is not None else 0
    return matched, missing


def main() -> None:
    args = _build_parser().parse_args()
    started = time.perf_counter()

    documents_path = Path(args.documents_path).expanduser().resolve()
    if not documents_path.exists():
        print(f"Input file not found: {documents_path}", file=sys.stderr)
        sys.exit(1)

    rows, dim = _read_documents(documents_path, strict=args.strict)
    password = _require_env("NEO4J_PASSWORD")
    neo4j = _import_neo4j()

    total = len(rows)
    processed = 0
    matched_total = 0
    missing_total = 0

    with neo4j.GraphDatabase.driver(
        args.neo4j_uri, auth=(args.neo4j_user, password)
    ) as driver:
        with driver.session(database=args.neo4j_database) as session:
            for start in range(0, total, args.batch_size):
                batch = rows[start : start + args.batch_size]
                matched, missing = session.execute_write(
                    _upsert_batch_tx,
                    rows=batch,
                    label=args.label,
                    id_property=args.id_property,
                    embedding_property=args.embedding_property,
                )
                processed += len(batch)
                matched_total += matched
                missing_total += missing
                if args.progress_every > 0 and processed % args.progress_every == 0:
                    elapsed = time.perf_counter() - started
                    print(
                        f"  imported {processed}/{total} embeddings "
                        f"(matched={matched_total}, missing={missing_total}, elapsed={elapsed:.1f}s)"
                    )

        create_vector_index(
            driver=driver,
            name=args.vector_index_name,
            label=args.label,
            embedding_property=args.embedding_property,
            dimensions=dim,
            similarity_fn=args.similarity_fn,
            fail_if_exists=False,
            neo4j_database=args.neo4j_database,
        )

    elapsed = time.perf_counter() - started
    print("Done.")
    print(f"Documents:        {documents_path}")
    print(f"Rows processed:   {processed}")
    print(f"Matched nodes:    {matched_total}")
    print(f"Missing nodes:    {missing_total}")
    print(f"Embedding dim:    {dim}")
    print(f"Vector index:     {args.vector_index_name}")
    print(f"Elapsed seconds:  {elapsed:.2f}")


if __name__ == "__main__":
    main()
