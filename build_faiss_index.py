from __future__ import annotations

import argparse
import json
import os
import sys
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def _import_faiss():
    try:
        import faiss
    except ImportError as exc:
        raise ImportError(
            "Could not import faiss. Install with `uv pip install faiss-cpu` "
            "or on GPU machine use `faiss-gpu`."
        ) from exc
    return faiss


def _import_numpy():
    try:
        import numpy as np
    except ImportError as exc:
        raise ImportError("Could not import numpy. Install with `uv pip install numpy`.") from exc
    return np


def _create_embedder(backend: str, model: str):
    if backend == "ollama":
        from neo4j_graphrag.embeddings import OllamaEmbeddings

        return OllamaEmbeddings(model=model)
    if backend == "sentence-transformers":
        from neo4j_graphrag.embeddings import SentenceTransformerEmbeddings

        return SentenceTransformerEmbeddings(model=model)
    raise ValueError(f"Unsupported backend: {backend}")


@dataclass
class ChunkRow:
    chunk_id: str
    text: str
    raw: dict[str, Any]


def _read_chunks(
    path: Path,
    *,
    text_key: str,
    chunk_id_key: str,
    strict: bool,
) -> list[ChunkRow]:
    rows: list[ChunkRow] = []
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            raw_line = line.strip()
            if not raw_line:
                continue
            try:
                payload = json.loads(raw_line)
            except json.JSONDecodeError as exc:
                if strict:
                    raise ValueError(f"Invalid JSON at line {line_no}: {exc}") from exc
                print(f"[warn] skip invalid JSON line {line_no}: {exc}", file=sys.stderr)
                continue

            chunk_id = payload.get(chunk_id_key)
            text = payload.get(text_key)
            if not chunk_id or not isinstance(chunk_id, str):
                if strict:
                    raise ValueError(f"Missing/invalid '{chunk_id_key}' at line {line_no}")
                print(
                    f"[warn] skip line {line_no}: missing string '{chunk_id_key}'",
                    file=sys.stderr,
                )
                continue
            if not text or not isinstance(text, str):
                if strict:
                    raise ValueError(f"Missing/invalid '{text_key}' at line {line_no}")
                print(
                    f"[warn] skip line {line_no}: missing string '{text_key}'",
                    file=sys.stderr,
                )
                continue

            rows.append(ChunkRow(chunk_id=chunk_id, text=text, raw=payload))
    return rows


def _close_embedder(embedder: Any) -> None:
    if hasattr(embedder, "client") and hasattr(embedder.client, "_client"):
        embedder.client._client.close()


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build FAISS dense index from chunks.ndjson (chunk_id-aligned)."
    )
    parser.add_argument(
        "--chunks-path",
        default="chunks.ndjson",
        help="Input NDJSON generated by ingest_chunks.py",
    )
    parser.add_argument(
        "--index-out",
        default="artifacts/faiss/chunks.index",
        help="Output FAISS index path.",
    )
    parser.add_argument(
        "--mapping-out",
        default="artifacts/faiss/intid_to_chunkid.jsonl",
        help="Output int_id -> chunk_id mapping JSONL path.",
    )
    parser.add_argument(
        "--meta-out",
        default="artifacts/faiss/meta.json",
        help="Output metadata JSON path.",
    )
    parser.add_argument(
        "--text-key",
        default="text",
        help="Text field key in chunks NDJSON.",
    )
    parser.add_argument(
        "--chunk-id-key",
        default="chunk_id",
        help="Chunk id field key in chunks NDJSON.",
    )
    parser.add_argument(
        "--embedder-backend",
        choices=["ollama", "sentence-transformers"],
        default="ollama",
        help="Embedding backend.",
    )
    parser.add_argument(
        "--embedder-model",
        default=os.environ.get("OLLAMA_EMBEDDER_MODEL", "bge-m3:latest"),
        help="Embedding model identifier.",
    )
    parser.add_argument(
        "--no-normalize",
        action="store_true",
        help="Disable L2 normalization before IndexFlatIP search.",
    )
    parser.add_argument(
        "--index-type",
        choices=["flatip", "hnsw"],
        default="flatip",
        help="FAISS index type. Start with flatip; use hnsw when data grows.",
    )
    parser.add_argument("--hnsw-m", type=int, default=32, help="HNSW M parameter.")
    parser.add_argument(
        "--hnsw-ef-construction",
        type=int,
        default=200,
        help="HNSW efConstruction parameter.",
    )
    parser.add_argument(
        "--progress-every",
        type=int,
        default=50,
        help="Print progress every N chunks.",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Fail fast on malformed input rows.",
    )
    parser.add_argument(
        "--on-embed-error",
        choices=["fail", "skip"],
        default="fail",
        help="Behavior when embedding generation fails for a chunk.",
    )
    return parser


def main() -> None:
    args = _build_parser().parse_args()

    faiss = _import_faiss()
    np = _import_numpy()

    chunks_path = Path(args.chunks_path)
    if not chunks_path.exists():
        print(f"Input file not found: {chunks_path}", file=sys.stderr)
        sys.exit(1)

    rows = _read_chunks(
        chunks_path,
        text_key=args.text_key,
        chunk_id_key=args.chunk_id_key,
        strict=args.strict,
    )
    if not rows:
        print("No valid chunks found in input.", file=sys.stderr)
        sys.exit(1)

    print(f"Loaded {len(rows)} chunks from {chunks_path}")
    print(
        f"Embedding backend={args.embedder_backend} model={args.embedder_model} "
        f"index_type={args.index_type}"
    )

    embedder = _create_embedder(args.embedder_backend, args.embedder_model)
    vectors: list[list[float]] = []
    indexed_rows: list[ChunkRow] = []
    skipped_embed = 0
    started = time.perf_counter()
    try:
        for i, row in enumerate(rows, start=1):
            try:
                vector = embedder.embed_query(row.text)
                vector_arr = np.asarray(vector, dtype="float32")
                if vector_arr.ndim != 1:
                    raise ValueError(f"invalid embedding shape: {vector_arr.shape}")
                if not np.isfinite(vector_arr).all():
                    raise ValueError("embedding contains non-finite values (NaN/Inf)")
            except Exception as exc:
                skipped_embed += 1
                message = (
                    f"[warn] embed failed at {i}/{len(rows)} "
                    f"chunk_id={row.chunk_id}: {exc}"
                )
                if args.on_embed_error == "skip":
                    print(message, file=sys.stderr)
                    continue
                raise

            vectors.append(vector_arr.tolist())
            indexed_rows.append(row)
            if args.progress_every > 0 and i % args.progress_every == 0:
                elapsed = time.perf_counter() - started
                print(f"  embedded {i}/{len(rows)} chunks ({elapsed:.1f}s)")
    finally:
        _close_embedder(embedder)

    if not indexed_rows:
        print("No vectors indexed (all embeddings failed).", file=sys.stderr)
        sys.exit(1)

    matrix = np.asarray(vectors, dtype="float32")
    if matrix.ndim != 2:
        print(f"Embedding matrix has invalid shape: {matrix.shape}", file=sys.stderr)
        sys.exit(1)
    dim = int(matrix.shape[1])
    if dim <= 0:
        print("Embedding dimension must be > 0", file=sys.stderr)
        sys.exit(1)

    if not args.no_normalize:
        faiss.normalize_L2(matrix)

    if args.index_type == "flatip":
        base_index = faiss.IndexFlatIP(dim)
    else:
        base_index = faiss.IndexHNSWFlat(dim, args.hnsw_m, faiss.METRIC_INNER_PRODUCT)
        base_index.hnsw.efConstruction = args.hnsw_ef_construction

    index = faiss.IndexIDMap2(base_index)
    int_ids = np.arange(matrix.shape[0], dtype="int64")
    index.add_with_ids(matrix, int_ids)

    index_out = Path(args.index_out)
    mapping_out = Path(args.mapping_out)
    meta_out = Path(args.meta_out)
    index_out.parent.mkdir(parents=True, exist_ok=True)
    mapping_out.parent.mkdir(parents=True, exist_ok=True)
    meta_out.parent.mkdir(parents=True, exist_ok=True)

    faiss.write_index(index, str(index_out))
    with mapping_out.open("w", encoding="utf-8") as f:
        for int_id, row in enumerate(indexed_rows):
            payload = {
                "int_id": int_id,
                "chunk_id": row.chunk_id,
                "doc_id": row.raw.get("doc_id"),
                "chunk_index": row.raw.get("chunk_index"),
                "section_name": row.raw.get("section_name"),
                "source_type": row.raw.get("source_type"),
            }
            f.write(json.dumps(payload, ensure_ascii=False) + "\n")

    meta = {
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "chunks_path": str(chunks_path),
        "index_path": str(index_out),
        "mapping_path": str(mapping_out),
        "count_input": len(rows),
        "count_indexed": len(indexed_rows),
        "count_skipped_embed_error": skipped_embed,
        "dimension": dim,
        "embedder_backend": args.embedder_backend,
        "embedder_model": args.embedder_model,
        "normalized": not args.no_normalize,
        "index_type": args.index_type,
    }
    meta_out.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")

    elapsed = time.perf_counter() - started
    print("Done.")
    print(f"Index:   {index_out}")
    print(f"Mapping: {mapping_out}")
    print(f"Meta:    {meta_out}")
    print(
        f"Vectors indexed: {len(indexed_rows)}/{len(rows)} "
        f"(skipped={skipped_embed}) | dim={dim} | elapsed={elapsed:.1f}s"
    )


if __name__ == "__main__":
    main()
